export interface CorpusEntry {
  readonly id: string;
  readonly text: string;
  readonly label: "COLLECTION" | "SERVICE";
  readonly category?: CollectionCategory;
}

export function collectionCorpus(): CorpusEntry[] {
  const collection = Object.entries(COLLECTION).flatMap(([category, texts]) =>
    texts.map((text, index): CorpusEntry => ({ id: `col-${category.toLowerCase().replaceAll("_", "-")}-${String(index + 1).padStart(2, "0")}`, text, label: "COLLECTION", category: category as CollectionCategory })),
  );
  const adversarial = Object.entries(ADVERSARIAL).flatMap(([category, texts]) =>
    texts.map((text, index): CorpusEntry => ({ id: `col-adv-${category.toLowerCase().replaceAll("_", "-")}-${String(index + 1).padStart(2, "0")}`, text, label: "COLLECTION", category: category as CollectionCategory })),
  );
  const service = SERVICE.map((text, index): CorpusEntry => ({ id: `svc-${String(index + 1).padStart(2, "0")}`, text, label: "SERVICE" }));
  return [...collection, ...adversarial, ...service];
}
