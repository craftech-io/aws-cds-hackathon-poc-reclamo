const ACUTE = ["...#.", "..#.."];
const TILDE = [".#.#.", "#.#.."];
const DIAERESIS = [".#.#.", "....."];
const NONE = [".....", "....."];

const ACCENTED: Readonly<Record<string, readonly [string, readonly string[]]>> = {
  Á: ["A", ACUTE],
  É: ["E", ACUTE],
  Í: ["I", ACUTE],
  Ó: ["O", ACUTE],
  Ú: ["U", ACUTE],
  Ñ: ["N", TILDE],
  Ü: ["U", DIAERESIS],
};

/** The 9 rows of a character (uppercase), each 5 cells: `#` on, `.` off. */
export function glyph(character: string): readonly string[] {
  const upper = character.toUpperCase();
  const accented = ACCENTED[upper];
  if (accented) {
    const base = BASE[accented[0]];
    if (!base) throw new Error(`font: no base glyph for ${upper}`);
    return [...accented[1], ...base];
  }
  const base = BASE[upper];
  if (!base) throw new Error(`font: no glyph for U+${upper.charCodeAt(0).toString(16).padStart(4, "0")}`);
  return [...NONE, ...base];
}
