// Operations of core.openapi.yaml (docs/architecture-integrations.md §5), keyed by operationId.
// Every world route carries `worldId` in the path and the world's simulated instant in `X-Sim-Now`;
// the mock authorizes the world against the invoking role before anything else (403
// `CALLER_WORLD_DENIED`), so 403 is on every world route.
import { CustomerId, Health, LoanId, NoParams, ResourceId, WorldHeaders, WorldParams } from "./common";
import {
  ChallengeCheckRequest,
  ChallengeCheckResult,
  ClosureRequest,
  ClosureResult,
  Customer,
  CustomerRef,
  DataChangeRequest,
  DataChangeResult,
  FreezeRequest,
  FreezeResult,
  LiveRecipient,
  OperationList,
  OperationsQuery,
  PhoneHash,
  TransferReversalCreditRequest,
  TransferReversalCreditResult,
  WhatsAppOptOutRequest,
  WhatsAppOptOutResult,
} from "./core-accounts";
import {
  ChargeCheck,
  ChargeReversalRequest,
  ChargeReversalResult,
  Disbursement,
  DuplicateCheck,
  DuplicateCheckRequest,
  InstalmentList,
  Loan,
  PaymentRequest,
  PaymentResult,
  PayoffQuote,
  PayoffQuoteRequest,
  RefundRequest,
  RefundResult,
} from "./core-loans";
import { defineRoute } from "./routes";

const world = WorldParams;
const customer = world.extend({ customerId: CustomerId });
const loan = world.extend({ loanId: LoanId });
const charge = world.extend({ chargeId: ResourceId });

const READ = [400, 403, 404, 503] as const;
const MONEY = [400, 403, 404, 409, 422, 503] as const;

export const coreRoutes = {
  getCustomerByPhone: defineRoute({
    method: "get",
    path: "/v1/{worldId}/customers/by-phone/{phoneHash}",
    params: world.extend({ phoneHash: PhoneHash }),
    headers: WorldHeaders,
    ok: CustomerRef,
    errors: READ,
  }),
  getCustomer: defineRoute({
    method: "get",
    path: "/v1/{worldId}/customers/{customerId}",
    params: customer,
    headers: WorldHeaders,
    ok: Customer,
    errors: READ,
  }),
  getLiveRecipient: defineRoute({
    method: "get",
    path: "/v1/{worldId}/customers/{customerId}/live-recipient",
    params: customer,
    headers: WorldHeaders,
    ok: LiveRecipient,
    errors: READ,
  }),
  checkChallenge: defineRoute({
    method: "post",
    path: "/v1/{worldId}/customers/{customerId}/challenge-check",
    params: customer,
    headers: WorldHeaders,
    body: ChallengeCheckRequest,
    ok: ChallengeCheckResult,
    errors: [400, 403, 404, 422, 503],
  }),
  listOperations: defineRoute({
    method: "get",
    path: "/v1/{worldId}/customers/{customerId}/operations",
    params: customer,
    query: OperationsQuery,
    headers: WorldHeaders,
    ok: OperationList,
    errors: READ,
  }),
  getLoan: defineRoute({ method: "get", path: "/v1/{worldId}/loans/{loanId}", params: loan, headers: WorldHeaders, ok: Loan, errors: READ }),
  listInstalments: defineRoute({
    method: "get",
    path: "/v1/{worldId}/loans/{loanId}/instalments",
    params: loan,
    headers: WorldHeaders,
    ok: InstalmentList,
    errors: READ,
  }),
  applyPayment: defineRoute({
    method: "post",
    path: "/v1/{worldId}/loans/{loanId}/payments",
    params: loan,
    headers: WorldHeaders,
    body: PaymentRequest,
    ok: PaymentResult,
    errors: MONEY,
  }),
  checkCharge: defineRoute({
    method: "post",
    path: "/v1/{worldId}/charges/{chargeId}/check",
    params: charge,
    headers: WorldHeaders,
    ok: ChargeCheck,
    errors: READ,
  }),
  reverseCharge: defineRoute({
    method: "post",
    path: "/v1/{worldId}/charges/{chargeId}/reversal",
    params: charge,
    headers: WorldHeaders,
    body: ChargeReversalRequest,
    ok: ChargeReversalResult,
    errors: MONEY,
  }),
  checkDuplicateDebit: defineRoute({
    method: "post",
    path: "/v1/{worldId}/loans/{loanId}/duplicate-check",
    params: loan,
    headers: WorldHeaders,
    body: DuplicateCheckRequest,
    ok: DuplicateCheck,
    errors: READ,
  }),
  refundDuplicateDebit: defineRoute({
    method: "post",
    path: "/v1/{worldId}/refunds",
    params: world,
    headers: WorldHeaders,
    body: RefundRequest,
    ok: RefundResult,
    errors: MONEY,
  }),
  setOutgoingFreeze: defineRoute({
    method: "post",
    path: "/v1/{worldId}/wallets/{customerId}/freeze",
    params: customer,
    headers: WorldHeaders,
    body: FreezeRequest,
    ok: FreezeResult,
    errors: READ,
  }),
  creditTransferReversal: defineRoute({
    method: "post",
    path: "/v1/{worldId}/wallets/{customerId}/transfer-reversals",
    params: customer,
    headers: WorldHeaders,
    body: TransferReversalCreditRequest,
    ok: TransferReversalCreditResult,
    errors: MONEY,
  }),
  quoteEarlyPayoff: defineRoute({
    method: "post",
    path: "/v1/{worldId}/loans/{loanId}/payoff-quote",
    params: loan,
    headers: WorldHeaders,
    body: PayoffQuoteRequest,
    ok: PayoffQuote,
    errors: [400, 403, 404, 422, 503],
  }),
  recordWhatsAppOptOut: defineRoute({
    method: "post",
    path: "/v1/{worldId}/customers/{customerId}/whatsapp/opt-out",
    params: customer,
    headers: WorldHeaders,
    body: WhatsAppOptOutRequest,
    ok: WhatsAppOptOutResult,
    errors: READ,
  }),
  requestClosure: defineRoute({
    method: "post",
    path: "/v1/{worldId}/customers/{customerId}/closure",
    params: customer,
    headers: WorldHeaders,
    body: ClosureRequest,
    ok: ClosureResult,
    errors: [400, 403, 404, 409, 503],
  }),
  requestDataChange: defineRoute({
    method: "post",
    path: "/v1/{worldId}/customers/{customerId}/data-change",
    params: customer,
    headers: WorldHeaders,
    body: DataChangeRequest,
    ok: DataChangeResult,
    errors: [400, 403, 404, 409, 503],
  }),
  getDisbursement: defineRoute({
    method: "get",
    path: "/v1/{worldId}/loans/{loanId}/disbursement",
    params: loan,
    headers: WorldHeaders,
    ok: Disbursement,
    errors: READ,
  }),
  getCoreHealth: defineRoute({ method: "get", path: "/v1/health", params: NoParams, ok: Health, errors: [503] }),
};
